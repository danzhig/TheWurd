const GENERATED = '_Generated by `pnpm content:build`. Do not edit by hand._';

function esc(s: string): string {
  return s.replace(/\|/g, '\\|');
}

function snippet(text: string, n = 8, from: 'start' | 'end' = 'start'): string {
  const w = text.split(/\s+/).filter(Boolean);
  if (w.length <= n) return text;
  return from === 'start' ? `${w.slice(0, n).join(' ')} …` : `… ${w.slice(-n).join(' ')}`;
}

/** Group renumbered plan verses into runs with a constant offset, per source record. */
function runs(m: BookMapping): { plan: string; webc: string; source: string }[] {
  const entries = [...m.renumbered].sort((a, b) => {
    const pa = a.plan.split(':');
    const pb = b.plan.split(':');
    const ca = /^\d+$/.test(pa[0]!) ? Number(pa[0]) : -1;
    const cb = /^\d+$/.test(pb[0]!) ? Number(pb[0]) : -1;
    return ca - cb || pa[0]!.localeCompare(pb[0]!) || Number(pa[1]) - Number(pb[1]);
  });
  const out: { plan: string[]; webc: string[][]; source: string }[] = [];
  for (const e of entries) {
    const last = out.at(-1);
    const prevPlan = last?.plan.at(-1);
    const prevWebc = last?.webc.at(-1);
    const contiguous =
      last &&
      last.source === e.source &&
      prevPlan!.split(':')[0] === e.plan.split(':')[0] &&
      Number(prevPlan!.split(':')[1]) + 1 === Number(e.plan.split(':')[1]) &&
      e.webc.length === 1 &&
      prevWebc!.length === 1 &&
      m.unitOrder.get(e.webc[0]!)! === m.unitOrder.get(prevWebc![0]!)! + 1;
    if (contiguous) {
      last.plan.push(e.plan);
      last.webc.push(e.webc);
    } else out.push({ plan: [e.plan], webc: [e.webc], source: e.source });
  }
  return out.map((r) => {
    const p0 = r.plan[0]!;
    const p1 = r.plan.at(-1)!;
    const plan =
      p0 === p1
        ? p0
        : p0.split(':')[0] === p1.split(':')[0]
          ? `${p0}–${p1.split(':')[1]}`
          : `${p0}–${p1}`;
    const units = [...new Set(r.webc.flat())].sort(
      (a, b) => m.unitOrder.get(a)! - m.unitOrder.get(b)!,
    );
    return { plan, webc: formatUnits(units), source: r.source };
  });
}

export function versificationLog(
  plan: ReadingPlan,
  mappings: Map<string, BookMapping>,
  resolution: Resolution,
  sectionFiles: SectionFile[],
): string {
  const L: string[] = [];
  L.push('# Versification log', '', GENERATED, '');
  L.push(
    "Plan references use Catholic numbering (Hebrew-based for the protocanonical books, as in NABRE). WEBC numbers the protocanonical Old Testament the English way. For each Hebrew-numbered book the pipeline reads the STEPBible TVTMS records, runs each record's own tests against WEBC to prove WEBC follows the English column there, and then maps Hebrew → English. Esther and Daniel are mapped by content (see `docs/esther-daniel-map.md`). Tobit, Judith, 1 Maccabees, Luke, John and Acts use the same numbers in the plan and in WEBC; their partial ranges are proven by anchors.",
    '',
  );

  const decisions = resolution.decisions;
  L.push('## Verse placements', '');
  if (!decisions.length) L.push('None needed.', '');
  else {
    L.push(
      'WEBC cannot divide these verses, so each is placed by the rule shown. Every placement must be approved in `content/plan/decisions.json`; an unapproved one stops the build.',
      '',
      '| WEBC verse | Kind | Plan sections that touch it | Placed in | Why | Approved |',
      '| --- | --- | --- | --- | --- | --- |',
    );
    for (const d of decisions) {
      L.push(
        `| ${d.unit} | ${d.kind} | ${esc(d.candidates.join('; '))} | **${d.assignedTo}** | ${esc(d.detail)} | ${d.approved ?? '**not yet**'} |`,
      );
    }
    L.push('');
  }

  L.push('## Sections whose text differs from reading the plan numbers directly in WEBC', '');
  L.push(
    'If you looked up each plan range in a WEBC (English-numbered) Bible, these are the sections where you would get different verses. "Moves in" and "moves out" list the difference.',
    '',
    '| Section | Title | Plan range (Catholic) | WEBC range | Moves in | Moves out |',
    '| --- | --- | --- | --- | --- | --- |',
  );
  for (const sf of sectionFiles) {
    const m = mappings.get(sf.bookId)!;
    if (m.kind === 'structure') continue; // listed in esther-daniel-map.md
    const actual = sf.verses.map((v) => v.ref);
    const d = numberingDiff(sf.range, actual, m);
    const note = d.error ? ` (${d.error} in WEBC)` : '';
    const { movesIn, movesOut } = d;
    if (movesIn.length || movesOut.length || note) {
      L.push(
        `| ${sf.id} | ${esc(sf.title)} | ${sf.bookId} ${sf.range}${note} | ${sf.bookId} ${sf.webcRange} | ${listRuns(movesIn, m) || '—'} | ${note ? '—' : listRuns(movesOut, m) || '—'} |`,
      );
    }
  }
  L.push('');

  L.push('## Every renumbered plan reference', '');
  L.push('Plan verse (Hebrew numbering) → WEBC verse, with the TVTMS record that defines it.', '');
  for (const pb of plan.books) {
    const m = mappings.get(pb.id)!;
    if (m.kind !== 'tvtms' || !m.renumbered.length) continue;
    L.push(`### ${pb.name}`, '', '| Plan | WEBC | Source |', '| --- | --- | --- |');
    for (const r of runs(m)) L.push(`| ${r.plan} | ${r.webc} | ${esc(r.source)} |`);
    for (const o of m.orphans)
      L.push(`| (none) | ${formatUnits([o.unit])} | ${esc(o.source)}: no Hebrew counterpart |`);
    L.push('');
  }

  L.push('## TVTMS records checked against WEBC', '');
  L.push(
    "`applied` = WEBC passed the English column's tests and failed the Hebrew column's, so the mapping was used. `same-tests` = the columns differ only in subverses WEBC does not have. Records where both columns agree are omitted.",
    '',
    '| Book | Record | Decision | English tests | Hebrew tests |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const pb of plan.books) {
    for (const r of mappings.get(pb.id)!.recordChecks) {
      if (r.decision === 'identical') continue;
      L.push(
        `| ${pb.id} | ${r.header} (line ${r.line}) | ${r.decision} | ${r.english.join(', ')} | ${r.hebrew.join(', ')} |`,
      );
    }
  }
  L.push('');
  return L.join('\n');
}

/** Format a set of refs as contiguous runs, e.g. '31:55' or '25:19, 26:1'. */
function listRuns(refs: string[], m: BookMapping): string {
  const sorted = [...refs].sort((x, y) => (m.unitOrder.get(x) ?? 0) - (m.unitOrder.get(y) ?? 0));
  const out: string[][] = [];
  for (const r of sorted) {
    const last = out.at(-1);
    if (last && m.unitOrder.get(r) === (m.unitOrder.get(last.at(-1)!) ?? -9) + 1) last.push(r);
    else out.push([r]);
  }
  return out.map((run) => formatUnits(run)).join(', ');
}

export function estherDanielMap(
  plan: ReadingPlan,
  mappings: Map<string, BookMapping>,
  maps: StructureMaps,
  resolution: Resolution,
  sectionFiles: SectionFile[],
): string {
  const L: string[] = [];
  L.push('# Esther and Daniel: how each section lands in WEBC', '', GENERATED, '');
  L.push(
    "WEBC contains only the Greek forms of Esther and Daniel (docs/PLAN.md D3). The plan uses NABRE references. The mapping below comes from `content/plan/structure-maps.json`; every row's content check is verified against WEBC by the pipeline. Opening and closing words are copied from WEBC by code.",
    '',
  );
  for (const id of ['Esth', 'Dan']) {
    const spec = maps.books[id]!;
    const approval = spec.approval
      ? `**Approved** by ${spec.approval.by} on ${spec.approval.date} (fingerprint \`${spec.approval.fingerprint}\`). Any change to this book's mapping fails the build until it is approved again.`
      : '**Not yet approved.**';
    const m = mappings.get(id)!;
    const pb = plan.books.find((b) => b.id === id)!;
    const byRef = new Map(m.units.map((u) => [u.ref, u]));
    L.push(`## ${pb.name}`, '', approval, '', spec.source, '');
    if (spec.splits.length) {
      L.push('**Divided verses**', '');
      for (const s of spec.splits) L.push(`- WEBC ${s.ref}: ${s.why}`);
      L.push('');
    }
    L.push(
      '**Where plan numbering and WEBC differ**',
      '',
      '| Plan (NABRE) | WEBC | Why |',
      '| --- | --- | --- |',
    );
    for (const s of spec.segments) L.push(`| ${s.plan} | ${s.webc} | ${esc(s.why)} |`);
    L.push('', 'Everything else has the same chapter and verse number in both.', '');
    L.push(
      '**Sections**',
      '',
      '| Section | Title | Plan range | WEBC range | Opens | Closes |',
      '| --- | --- | --- | --- | --- | --- |',
    );
    for (const sf of sectionFiles.filter((s) => s.bookId === id)) {
      const first = byRef.get(sf.verses[0]!.ref)!;
      const last = byRef.get(sf.verses.at(-1)!.ref)!;
      L.push(
        `| ${sf.id} | ${esc(sf.title)} | ${sf.range} | ${sf.webcRange} | ${first.ref.split('.').slice(1).join(':').replace(':', ':')} “${esc(snippet(first.text))}” | ${last.ref.split('.').slice(1).join(':')} “${esc(snippet(last.text, 8, 'end'))}” |`,
      );
      for (const f of sf.folds)
        L.push(`| ↳ fold | ${esc(f.label)} (${f.status}) | ${f.range} | ${f.webcRange} | | |`);
    }
    L.push(
      '',
      '**Content checks**',
      '',
      '| Where | Plan ref | WEBC | Must contain | Result |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const a of resolution.anchors.filter(
      (x) =>
        mappings.get(id) &&
        (x.sectionId.startsWith(id.toLowerCase()) || x.sectionId === `structure-map:${id}`),
    )) {
      L.push(
        `| ${a.sectionId} | ${a.ref} | ${a.webc.join(', ')} | ${a.mustContain.map((w) => `«${w}»`).join(' ')} | ${a.missing.length ? `**FAIL** (missing ${a.missing.map((w) => `«${w}»`).join(' ')})` : 'ok'} |`,
      );
    }
    L.push('');
  }
  const esthGaps = missingVerses(mappings.get('Esth')!);
  if (esthGaps.length) {
    L.push(
      '## Verses WEBC does not have',
      '',
      `Greek Esther in WEBC has no verse ${esthGaps.join(', ')}. The plan's whole-chapter ranges are unaffected.`,
      '',
    );
  }
  return L.join('\n');
}

function missingVerses(m: BookMapping): string[] {
  const out: string[] = [];
  const seen = new Map<number, Set<number>>();
  for (const u of m.units) {
    const s = seen.get(u.c) ?? new Set<number>();
    s.add(u.v);
    seen.set(u.c, s);
  }
  for (const [c, s] of seen) {
    const max = Math.max(...s);
    for (let v = 1; v < max; v++) if (!s.has(v)) out.push(`${c}:${v}`);
  }
  return out;
}

export function traditionSummary(
  bookId: string,
  records: TvtmsRecord[],
  parsed: ParsedBook,
): { column: string; pass: number; fail: number }[] {
  const tv = CANON_BY_ID.get(bookId)!.tvtms;
  const tally = new Map<string, { pass: number; fail: number }>();
  for (const r of records.filter((x) => x.book === tv)) {
    r.columns.forEach((col, i) => {
      const res = r.tests.map((t) => evaluateTest(t[i] ?? '', parsed.chapterLengths, tv));
      if (!res.some((x) => x !== 'unknown')) return;
      const t = tally.get(col) ?? { pass: 0, fail: 0 };
      if (res.includes('fail')) t.fail++;
      else t.pass++;
      tally.set(col, t);
    });
  }
  return [...tally].map(([column, t]) => ({ column, ...t }));
}

export function pipelineReport(args: {
  ok: boolean;
  errors: string[];
  plan: ReadingPlan;
  parsed: Map<string, ParsedBook>;
  mappings: Map<string, BookMapping>;
  resolution: Resolution;
  records: TvtmsRecord[];
  sectionFiles: SectionFile[];
  sizes: { id: string; bytes: number; gzipBytes: number }[];
  emitted: boolean;
}): string {
  const { ok, errors, plan, parsed, mappings, resolution, records, sectionFiles, sizes, emitted } =
    args;
  const L: string[] = [];
  L.push('# Content pipeline report', '', GENERATED, '');
  L.push(
    `**Status: ${ok ? 'PASS' : 'FAIL'}**${emitted ? '' : ' — `public/data` was not written because the checks below failed.'}`,
    '',
  );
  const totalUnits = plan.books.reduce((n, b) => n + mappings.get(b.id)!.units.length, 0);
  L.push(
    `- Plan books: ${plan.books.length} (${plan.books.map((b) => b.id).join(', ')})`,
    `- Sections: ${sectionFiles.length}`,
    `- WEBC verses covered: ${totalUnits}, each exactly once`,
    `- Anchors and content checks: ${resolution.anchors.length} (${resolution.anchors.filter((a) => a.missing.length).length} failing)`,
    '',
  );
  L.push('## Errors (stop the build)', '');
  if (!errors.length) L.push('None.', '');
  else for (const e of errors) L.push(`- ${e}`);
  L.push('');
  L.push(
    '## Verse placements',
    '',
    'Details in `docs/versification-log.md` → "Verse placements".',
    '',
  );
  for (const d of resolution.decisions) {
    L.push(
      `- ${d.unit} → ${d.assignedTo} (${d.kind}) — ${d.approved ? `approved ${d.approved}` : '**not approved**'}`,
    );
  }
  L.push('');

  L.push(
    '## Anchors',
    '',
    '| Section | Plan ref | WEBC | Must contain | Result |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const a of resolution.anchors) {
    L.push(
      `| ${a.sectionId} | ${a.ref} | ${a.webc.join(', ')} | ${a.mustContain.map((w) => `«${w}»`).join(' ')} | ${a.missing.length ? `**FAIL** (missing ${a.missing.map((w) => `«${w}»`).join(' ')})` : 'ok'} |`,
    );
  }
  L.push('');

  L.push('## Text forms found in WEBC', '');
  const tob = traditionSummary('Tob', records, parsed.get('Tob')!);
  const tobFull = tob.filter((t) => t.fail === 0).map((t) => t.column);
  L.push(
    `- **Tobit**: WEBC passes every TVTMS test only for ${tobFull.map((c) => `"${c}"`).join(', ') || 'no single column'} (${tob.map((t) => `${t.column}: ${t.pass} pass / ${t.fail} fail`).join('; ')}). WEBC's Tobit therefore follows the KJV Apocrypha's numbering, which translates the shorter Greek text; NABRE translates the longer one (Codex Sinaiticus). All Tobit sections are whole chapters, so the plan is unaffected.`,
  );
  const inserted = [...parsed.values()]
    .filter((b) => b.spacesInserted)
    .map((b) => `${b.book.id} ${b.spacesInserted}`);
  if (inserted.length) {
    L.push(
      `- **Footnote spacing**: in ${inserted.reduce((n, s) => n + Number(s.split(' ')[1]), 0)} places WEBC's USFM puts a footnote caller between two words with no space (${inserted.join(', ')}). The pipeline inserts a space there so the words do not run together; no other change is made to the text.`,
    );
  }
  for (const id of ['Jdt', '1Macc']) {
    const t = traditionSummary(id, records, parsed.get(id)!);
    L.push(
      `- **${CANON_BY_ID.get(id)!.name}**: ${t.map((x) => `${x.column}: ${x.pass} pass / ${x.fail} fail`).join('; ') || 'no TVTMS tests'}.`,
    );
  }
  L.push(
    '- **Esther**: Greek form with the additions merged into chapters 1–10 in [square brackets]; see `docs/esther-daniel-map.md`.',
    '- **Daniel**: Greek form; chapter 3 has 97 verses (Greek numbering), chapters 4–6 English numbering, Susanna = 13, Bel and the Dragon = 14.',
  );
  const empties = plan.books.flatMap((b) =>
    mappings
      .get(b.id)!
      .units.filter((u) => !u.text)
      .map((u) => u.ref),
  );
  if (empties.length) {
    L.push(
      `- **Empty verses** (number kept, text only in a footnote, as WEBC prints them): ${empties.join(', ')}. The reader will show the footnote in place of text.`,
    );
  }
  L.push('');

  L.push(
    '## Section file sizes',
    '',
    'Budget: under 60 KB gzipped per section (docs/PLAN.md §5).',
    '',
  );
  const over = sizes.filter((s) => s.gzipBytes > 60 * 1024);
  if (!over.length) L.push('All sections are within budget.', '');
  else {
    L.push('| Section | Status | Raw KB | Gzip KB |', '| --- | --- | --- | --- |');
    for (const s of over) {
      const sf = sectionFiles.find((x) => x.id === s.id)!;
      L.push(
        `| ${s.id} | ${sf.status} | ${(s.bytes / 1024).toFixed(0)} | ${(s.gzipBytes / 1024).toFixed(0)} |`,
      );
    }
    L.push(
      '',
      'These are long skipped ranges whose full text is built in (D6). M3 can load their text on demand when a fold is opened.',
      '',
    );
  }
  const largest = [...sizes].sort((a, b) => b.gzipBytes - a.gzipBytes).slice(0, 5);
  L.push(
    `Largest: ${largest.map((s) => `${s.id} ${(s.gzipBytes / 1024).toFixed(0)} KB`).join(', ')}.`,
    '',
  );
  return L.join('\n');
}
