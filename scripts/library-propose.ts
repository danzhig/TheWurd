/**
 * pnpm library:propose <bookId> — write docs/library/<bookId>-outline.md: the book's structure
 * from WEBC (chapters, verse counts, where paragraphs and poems start, the opening words of each
 * chapter, any heading WEBC prints), to draft section titles and ranges from. Text is copied from
 * the source, never typed. The proposal itself goes in docs/library/<bookId>-sections.md.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fetchSources } from './fetch-sources';
import { CANON_BY_ID } from './lib/canon';
import { DOCS_DIR } from './lib/paths';
import { readTvtmsCondensed } from './lib/tvtms';
import { buildMappings, readStructureMaps } from './map-versification';
import { STRUCTURE_MAPS } from './lib/paths';
import { parseAllBooks } from './parse-usfm';

async function main() {
  const id = process.argv[2];
  const book = id ? CANON_BY_ID.get(id) : undefined;
  if (!book) {
    console.error('Usage: pnpm library:propose <bookId>, e.g. Lev');
    process.exit(1);
  }
  const { webcDir, tvtms } = await fetchSources();
  const all = parseAllBooks(webcDir!);
  const parsed = all.get(book.id)!;
  const mapping = buildMappings(
    all,
    [book.id],
    readTvtmsCondensed(tvtms!),
    readStructureMaps(STRUCTURE_MAPS),
  ).get(book.id)!;
  const lines: string[] = [
    `# ${book.name}: outline from WEBC`,
    '',
    `Generated by \`pnpm library:propose ${book.id}\` from the WEBC text (copied, never typed). Use it to draft the sections in \`docs/library/${book.id}-sections.md\`.`,
    '',
    `${parsed.chapterLengths.length} chapters, ${parsed.verses.length} verses (WEBC numbering).`,
    '',
    '| Chapter | Verses | Paragraphs start at | Heading | Opens with |',
    '| --- | --- | --- | --- | --- |',
  ];
  // Section ranges use the plan's numbering (Catholic, Hebrew-based for this book); list where WEBC
  // numbers the same verse differently, so boundaries are drawn in the right numbering.
  if (mapping.renumbered.length) {
    const tail = lines.splice(lines.length - 2, 2);
    lines.push(
      `**Numbering:** section ranges use the plan's (Hebrew-based) numbering. WEBC numbers ${mapping.renumbered.length} verses of this book differently:`,
      '',
      ...mapping.renumbered
        .slice(0, 60)
        .map(
          (r) =>
            `- plan ${r.plan} = WEBC ${r.webc.map((u) => u.replace(/^[^.]+\./, '').replace('.', ':')).join(', ')}`,
        ),
      ...(mapping.renumbered.length > 60 ? [`- … and ${mapping.renumbered.length - 60} more`] : []),
      '',
      ...tail,
    );
  } else
    lines.splice(
      lines.length - 2,
      0,
      'Numbering: the plan and WEBC number this book the same way.',
      '',
    );
  parsed.chapterLengths.forEach((n, i) => {
    const c = i + 1;
    const vs = parsed.verses.filter((v) => v.c === c);
    const starts = vs
      .filter(
        (v, j) =>
          j === 0 ||
          v.blocks[0]?.brk ||
          /^q/.test(v.blocks[0]?.style ?? '') !== /^q/.test(vs[j - 1]?.blocks.at(-1)?.style ?? ''),
      )
      .map((v) => v.v);
    const heading = vs.find((v) => v.heading)?.heading ?? '';
    const words = (vs[0]?.text ?? '').split(/\s+/).slice(0, 10).join(' ');
    lines.push(
      `| ${c} | ${n} | ${starts.join(', ')} | ${heading.replace(/\|/g, '/')} | ${words.replace(/\|/g, '/')}… |`,
    );
  });
  fs.mkdirSync(path.join(DOCS_DIR, 'library'), { recursive: true });
  const out = path.join(DOCS_DIR, 'library', `${book.id}-outline.md`);
  fs.writeFileSync(out, `${lines.join('\n')}\n`);
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
