import type { Metadata } from 'next';
import Link from 'next/link';
import styles from '@/app/about/about.module.css';
import { getManifest } from '@/lib/data';

export const metadata: Metadata = {
  title: 'Sources · Scripture as Story',
  description: 'Every text, dataset and font this site is built from, with its license.',
};

/** Sources (PLAN §3, ground rule 5): every pinned source with its license and attribution. */
export default function SourcesPage() {
  const m = getManifest();
  const layers = [...new Set(m.sources.map((s) => s.layer))];
  return (
    <main className={styles.page} data-testid="sources">
      <nav className={styles.nav}>
        <Link href="/">← All books</Link>
      </nav>
      <header className={styles.header}>
        <p className="label">Scripture as Story</p>
        <h1 id="page-heading" tabIndex={-1} className="display">
          Sources
        </h1>
        <p className={styles.lede}>
          Everything on this site is built from openly licensed sources, each pinned to an exact
          version and checked when the site is built. The scripture text is reproduced unchanged.
        </p>
      </header>

      {layers.map((layer) => (
        <section key={layer} aria-labelledby={`layer-${slug(layer)}`}>
          <h2 id={`layer-${slug(layer)}`}>{layer}</h2>
          {m.sources
            .filter((s) => s.layer === layer)
            .map((s) => (
              <article key={s.id} className={styles.source} data-source={s.id}>
                <h3>
                  <a href={s.homepage}>{s.name}</a>
                </h3>
                <p>{s.attribution}</p>
                <dl className={styles.facts}>
                  <dt>License</dt>
                  <dd>
                    <a href={s.licenseUrl}>{s.license}</a>
                  </dd>
                  <dt>Used for</dt>
                  <dd>{s.usedFor}</dd>
                  <dt>Version</dt>
                  <dd>{s.version}</dd>
                </dl>
              </article>
            ))}
        </section>
      ))}

      <section aria-labelledby="made-here">
        <h2 id="made-here">Made for this site</h2>
        <p>
          The reading plan, its bridges and reader notes, and the one-line book descriptions were
          written for Scripture as Story. The clouds and paper grain are generated by code; no
          artwork is copied.
        </p>
      </section>

      <p className={styles.footer}>
        <Link href="/about/">About this path</Link> · <Link href="/path/">The path</Link>
      </p>
    </main>
  );
}

function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-');
}
