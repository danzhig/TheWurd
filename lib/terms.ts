/**
 * Key terms (PLAN §13): the authored input (`content/terms/<sectionId>.json`, citations only) and
 * the built cards (`public/data/terms/<sectionId>.json`, every form copied from the cited row).
 */
import { z } from 'zod';

const Status = z.enum(['candidate', 'draft', 'verified']);

/** What an author writes: which rows, which words, never the original-language forms themselves. */
export const TermInputSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9-]+$/),
    /** The verse in WEBC (English) numbering, OSIS style: "Gen.1.2". */
    ref: z.string(),
    /** The English words marked in WEBC, and which occurrence in the verse (1-based). */
    english: z.object({ text: z.string().min(1), occurrence: z.number().int().min(1).default(1) }),
    lang: z.enum(['hbo', 'arc', 'grc']),
    /** TAHOT/TAGNT rows: verse in English numbering and word position. */
    original: z
      .array(
        z.object({
          dataset: z.enum(['TAHOT', 'TAGNT']),
          ref: z.string(),
          wordIndex: z.number().int().min(1),
          /** The extended Strong's of the part that matters, when the word has several. */
          strongs: z.string().optional(),
        }),
      )
      .min(1),
    /** Swete's Septuagint: verse in its own numbering and word position. */
    lxx: z.array(z.object({ ref: z.string(), wordIndex: z.number().int().min(1) })).default([]),
    vulgate: z
      .object({
        ref: z.string(), // USFM key in the Vulgate's numbering, "GEN.1.2"
        words: z.string(), // must occur in that verse
        lewisShort: z.object({ key: z.string(), sense: z.string(), quote: z.string() }).optional(),
      })
      .optional(),
    /** Renderings in the comparison texts; each must occur in the cited verse. */
    renderings: z
      .array(
        z.object({
          version: z.enum(['drc', 'kjv', 'brenton']),
          ref: z.string(),
          words: z.string(),
        }),
      )
      .default([]),
    /**
     * "Why it is debated": original prose. It never types an original-language or scripture word;
     * placeholders {original}, {grammar}, {lxx}, {vulgate}, {webc}, {drc}, {kjv}, {brenton} are
     * filled from the cited data at build time.
     */
    debate: z.object({ text: z.string(), sources: z.array(z.string()).default([]) }).optional(),
    status: Status.default('draft'),
  })
  .strict();
export type TermInput = z.infer<typeof TermInputSchema>;

export const TermFileSchema = z.object({ terms: z.array(TermInputSchema) }).strict();

/** A built card deck for one term, ready for the reader. */
export interface BuiltTerm {
  id: string;
  sectionId: string;
  ref: string;
  status: z.infer<typeof Status>;
  /** Where the term sits in the WEBC verse's plain text (`verseText`). */
  span: { verse: string; start: number; end: number; text: string };
  title: string; // transliteration of the main original word, generated by code
  cards: Card[];
  citations: string[];
}

export type Card =
  | {
      kind: 'original';
      lang: 'hbo' | 'arc' | 'grc';
      words: {
        form: string;
        translit: string;
        lemma?: string;
        strongs: string;
        grammar: string;
        grammarText?: string;
        gloss?: string;
        meaning?: string[];
        cite: string;
      }[];
    }
  | {
      kind: 'septuagint';
      words: { form: string; translit: string; lemma?: string; cite: string }[];
      /** Swete's transcription has OCR slips: unverified forms must be checked against the print. */
      printCheck: boolean;
    }
  | {
      kind: 'vulgate';
      words: string;
      ref: string;
      sense?: { headword: string; text: string; cite: string };
    }
  | { kind: 'english'; renderings: { version: string; ref: string; words: string }[] }
  | { kind: 'debate'; text: string; sources: string[] };

export const VERSION_NAME: Record<string, string> = {
  webc: 'World English Bible Catholic',
  drc: 'Douay-Rheims',
  kjv: 'King James',
  brenton: 'Brenton (Septuagint)',
};

/** Drafts are shown everywhere except the production site (PLAN §18, check 13). */
export function visibleTerms(terms: BuiltTerm[], env = process.env.VERCEL_ENV): BuiltTerm[] {
  return env === 'production' ? terms.filter((t) => t.status === 'verified') : terms;
}
